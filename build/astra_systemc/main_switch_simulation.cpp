int sc_main(int argc, char** argv) {
    // Arguments are supplied by run_experiment.py:
    //   argv[1] num_ports      number of switch ports / NPUs (e.g. 16)
    //   argv[2] bytes_per_cell bytes per cell (e.g. 80)
    //   argv[3] workload_base  path to the .et traces WITHOUT the .<rank>.et
    //                          suffix (the driver builds this and also writes
    //                          the matching network/system config files).

    // std::cout << "arguments are in order: " << argv[0] << " " << argv[1] << " " << argv[2] << " " << argv[3] << " "
    //           << argv[4] << std::endl;
    if (argc != 5) {
        ASSERT_PRINT(
            false,
            "Usage: %s <num_ports> <bytes_per_cell> <workload_base> "
            "<astra_systemc_root>\n"
            "  num_ports:      number of switch ports / NPUs (e.g., 16)\n"
            "  bytes_per_cell: number of bytes per cell (e.g., 80, 128)\n"
            "  workload_base:  path to the STAGE/microbenchmark traces WITHOUT "
            "the .<rank>.et suffix\n",
            argv[0]);
    }

    const size_t numPorts = parseUnsignedArg(argv[1], "num_ports");
    const size_t bytesPerCell = parseUnsignedArg(argv[2], "bytes_per_cell");
    const std::string workload_config = argv[3];
    const std::string astra_systemc_root = argv[4];

    AstraSim::LoggerFactory::init("empty", astra_systemc_root + "/astrasim_log_factory");

    std::cout << "Starting SystemC AstraSim Simulation\n";

    // Config files are (re)generated by run_experiment.py right before this
    // binary is launched, so they always match the workload above.
    const std::string system_config =
        astra_systemc_root + "/config_files/my_system_config.json";

    const std::string comm_group_config = workload_config + ".json";

    const std::string remote_memory_configuration =
        astra_systemc_root + "/config_files/no_memory_expansion.json";

    const std::string run_name = "systemc_astrasim_test";

    const std::vector<int> physical_dims = {static_cast<int>(numPorts)};
    const std::vector<int> queues_per_dim = {1};

    constexpr double injection_scale = 1.0;
    // Never used by the simulation; kept only to satisfy the Sys constructor.
    constexpr double comm_scale = 1.0;
    constexpr bool rendezvous_enabled = false;

#if defined(USE_DSS)
    std::cout << "Using DSS switch model\n" << std::endl;
#elif defined(USE_HIERXBAR)
    std::cout << "Using Hierarchical Crossbar switch model\n" << std::endl;
#elif defined(XBAR)
    std::cout << "Using Crossbar switch model\n" << std::endl;
#endif

    std::cout << "numPorts: " << numPorts << ", bytesPerCell: " << bytesPerCell
              << ", workload: " << workload_config << std::endl;

    // ------------------------------------------------------------
    Packet::resetPacketID();

    sc_report_handler::set_verbosity_level(SC_HIGH);
    sc_report_handler::set_actions(SC_ERROR, SC_DISPLAY | SC_LOG);

    const auto t0 = std::chrono::steady_clock::now();

    ScPacketGen packetGen(numPorts, 50);
    packetGen.setHasPayload(true);
    packetGen.setPacketLength(10);

#if defined(USE_DSS)
    SwitchDSS swParadox(numPorts, "DSS", 1200000);
    ScSwitchDSS dut("paradox", swParadox, packetGen, 3);
    // dut.enableDebug(swParams.debugEnabled);
    // Required for AstraSim-driven traffic: routes driveProcess() through
    // m_packetGeneratorInterface (instead of synthetic ScPacketGen) and lets
    // setOrderedMergerDeliveryAll() below actually arm the mergers.
    dut.setAstraCsvTraceEnabled(true);
    dut.setOrderedMergerDeliveryAll(true);
#elif defined(USE_HIERXBAR)
    SwitchHierXbar swHierXbar(numPorts, 1200000, "HierXbar");
    ScSwitchHierXbar dut("hierXbar", swHierXbar, packetGen, 3);
#elif defined(XBAR)
    SwitchCrossbar swCrossbar(numPorts);
    ScSwitchBox dut("xbar", swCrossbar, 1200000, ArbiterType::roundRobin,
                    nullptr, 3, &packetGen);
#endif

#if defined(XBAR)
    dut.setPayloadEnabled(true);
#else
    dut.setPayloadEnabledAll(true);
#endif
    dut.setStatisticsParameters(20, 40);
    // TODO(logging-cleanup): flip to false to cut ~99% of test_log volume.
    // Keeps only the unconditional final "Simulation time:" print
    // (PacketGeneratorInterface.cpp:237) and printFinalStatsHeader()/printStats()
    // (below, near end of this function) as the summary.
    // dut.setCycleStatsEnabled(false);
    dut.setCycleStatsEnabled(false);
    dut.setActiveCycles(2000000);

    PacketGeneratorInterface packetGeneratorInterface(numPorts, bytesPerCell,
                                                      10);
    dut.setPacketGeneratorInterface(&packetGeneratorInterface);
    packetGeneratorInterface.setVerbose(false);

    // ------------------------------------------------------------
    std::vector<std::unique_ptr<SystemCScheduler>> schedulers;
    schedulers.reserve(static_cast<int>(numPorts));

    for (int i = 0; i < static_cast<int>(numPorts); ++i) {
        schedulers.emplace_back(std::make_unique<SystemCScheduler>(
            sc_core::sc_gen_unique_name("SystemCScheduler")));
    }

    std::vector<std::unique_ptr<AstraSim::MyNetworkAPI>> network_apis;
    network_apis.reserve(static_cast<int>(numPorts));
    for (int rank = 0; rank < static_cast<int>(numPorts); ++rank) {
        network_apis.emplace_back(std::make_unique<AstraSim::MyNetworkAPI>(
            rank, &packetGeneratorInterface, schedulers.at(rank).get()));
    }

    const auto memory_api =
        std::make_unique<Analytical::AnalyticalRemoteMemory>(
            remote_memory_configuration);

    std::vector<std::unique_ptr<AstraSim::Sys>> systems;
    systems.reserve(static_cast<int>(numPorts));
    for (int rank = 0; rank < static_cast<int>(numPorts); ++rank) {
        systems.emplace_back(std::make_unique<AstraSim::Sys>(
            rank, workload_config, comm_group_config, system_config,
            memory_api.get(), network_apis.at(rank).get(), physical_dims,
            queues_per_dim, injection_scale, comm_scale, rendezvous_enabled));
    }

    // Initiate ASTRA-sim simulation
    for (int i = 0; i < static_cast<int>(numPorts); i++) {
        systems[i]->workload->fire();
    }

    std::cout << "Starting SystemC simulation" << std::endl;
    sc_core::sc_start();

    for (int rank = 0; rank < static_cast<int>(numPorts); ++rank) {
        if (systems[rank]->pending_events != 0) {
            ASSERT_PRINT(false,
                         "Rank %d still has pending events at the end of "
                         "simulation: %zu\n",
                         rank, systems[rank]->pending_events);
        }
    }

    dut.printFinalStatsHeader();
    dut.printStats();

    const auto t1 = std::chrono::steady_clock::now();
    const std::chrono::duration<double> elapsed = t1 - t0;

    std::cout << ", " << elapsed.count() << "\n";

    // Destroy simulation objects while spdlog is still alive so their
    // destructors (e.g. Sys::~Sys -> exit_sim_loop) can log normally.
    // Calling LoggerFactory::shutdown() first would cause ~Sys() to
    // re-create a new spdlog thread pool after teardown, leaking its
    // internal heap strings (detected by LeakSanitizer).
    systems.clear();
    network_apis.clear();
    schedulers.clear();

    AstraSim::LoggerFactory::shutdown();
    return 0;
}
